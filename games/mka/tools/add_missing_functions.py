"""Add game functions the disassembly missed to street2's generated code.

They are reached only through a pointer the function detector did not follow
(e.g. a vtable slot), so every call was skipped with
"[ICALL] Failed to resolve VA". Regenerating all units would drop the
post-passes applied since, so each missing function is translated alone
(tools.recomp -f, same generator; the disassembly is redone with
hle/seed_functions.json + hle/seed_manual.json into recomp-work/disasm-extra)
into gen/recomp_extra.c, declared in recomp_funcs.h and inserted into the
sorted dispatch table. Idempotent. Same approach as
street1/hle/add-missing-functions.py.

usage: python tools/add_missing_functions.py   (from street2/)
"""
from pathlib import Path
import re
import subprocess

# Evidence per address in hle/seed_manual.json. 0x000A28A0 (vtable 0x2C0680
# slot 2, goal-replay update): without it the replay never ended and
# "A: Resume Game" was ignored. 0x000FA9A0: player creator. 0x000FA9A0 and
# 0x00213C19 sit where the disassembler still rejects the seed (an overlapping
# decode already starts there), so their entries were added to
# recomp-work/disasm-extra/functions.json by hand (ends 0xFABD5 / 0x213C5A).
# Street 2 values above; MK Armageddon fills this from its own ICALL failures.
# MK Armageddon: 0x002C8960 (ICALL Failed in run 20261104-024241; jump table of
# sub_002C85F0 at 0x2C8948 hid it). Entry added to disasm-extra/functions.json by hand.
# 2026-11-04 (run 20261104-124935): 0x002ED640 (log callback after the jump table of
# sub_002ED5D0), 0x0039BC5D (CRT thread start, SEH), 0x003A44A2 (thread exit callback),
# 0x0049BDCF (XNET switch, entry hidden behind sub_0049BD4A). Entries hand-added too.
# 2026-11-04 night (run 20261104-225159, after the process fibers): 0x004A6B40 (PSFD_I start) and
# 0x004A77C0 (PSFD_P start, a false start at 0x4A7800 hid it), 0x0031BCF0 (decoder with jump tables,
# ends 0x31F32B; bogus 0x318800/0x319800 blocks hid it). Entries hand-added.
# 0x00318260 (run 20261104-232737): sibling decoder, table 0x31B858, ends 0x31B858.
# 0x004A6510 (run 20261105-000111, starts where sub_004A62C0 ends) and its sibling 0x004A6050 (after the
# jump table at 0x4A6024; same prologue). Entries hand-added.
# 0x002C95D0 (run 20261105-012548, after LOGON.SFD; ends 0x2C9756). Entry hand-added.
# 0x00097E00 (process entry, ends 0x97F2C) and 0x00397F16 (loop head inside sub_00397EB0, ends after its
# jump table 0x397FA8), run 20261106-231001; 0x0034345D (shared `pop esi; ret 0xc` epilogue of a
# split function, run 20261106-234433 entering the main menu); 0x002B6900 (ICALL in the Arcade tower screen,
# run 20261107-005xxx; ends at its jump table 0x2B6AB8) after the title screen. Entries hand-added.
MISSING = [0x002C8960, 0x002ED640, 0x0039BC5D, 0x003A44A2, 0x0049BDCF, 0x004A6B40, 0x004A77C0, 0x0031BCF0, 0x00318260, 0x004A6510, 0x004A6050, 0x002C95D0, 0x00097E00, 0x00397F16, 0x0034345D, 0x002B6900]

street2 = Path(__file__).resolve().parent.parent
work = street2.parent
gen = street2 / 'project/src/recomp/gen'
python = work / 'recomp-python/Scripts/python.exe'
xbe = street2 / 'default.xbe'
rw = Path('D:/CodexBuilds/mka/recomp-work')

# Bodies already in recomp_extra.c are kept (translating one function redoes the whole disassembly, ~2 min);
# ADD_MISSING_FULL=1 retranslates everything.
import os
previous = (gen / 'recomp_extra.c').read_text(encoding='utf-8') if (gen / 'recomp_extra.c').is_file() else ''
bodies = []
for a in MISSING:
    old = re.search(rf'/\*\*\n \* sub_{a:08X}\n.*?\nvoid sub_{a:08X}\(void\)\n\{{.*?\n\}}\n', previous, re.S)
    if old and not os.environ.get('ADD_MISSING_FULL'):
        bodies.append(old.group(0))
        print(f'kept sub_{a:08X}')
        continue
    out = subprocess.run([str(python), '-m', 'tools.recomp', str(xbe), '-f', f'0x{a:X}',
                          '--game-name', 'Mortal Kombat Armageddon', '--disasm-dir', str(rw / 'disasm-extra'),
                          '--func-id-dir', str(rw / 'ident'), '--abi-dir', str(rw / 'abi')],
                         cwd=Path(__file__).resolve().parents[3], capture_output=True, text=True, check=True).stdout
    m = re.search(rf'/\*\*\n \* sub_{a:08X}\n.*?\nvoid sub_{a:08X}\(void\)\n\{{.*?\n\}}\n', out, re.S)
    if not m:
        raise SystemExit(f'no translation for {a:08X}')
    bodies.append(m.group(0))
    print(f'translated sub_{a:08X}')

(gen / 'recomp_extra.c').write_text(
    '/* Functions reached only through pointers the detector missed; see\n'
    ' * street2/tools/add_missing_functions.py. Generated by tools.recomp -f. */\n\n'
    '#define RECOMP_' 'GENERATED_CODE\n#include "recomp_funcs.h"\n#include <math.h>\n\n'
    + '\n'.join(bodies), encoding='utf-8', newline='\n')

funcs = gen / 'recomp_funcs.h'
text = funcs.read_text(encoding='utf-8')
for a in MISSING:
    decl = f'void sub_{a:08X}(void);\n'
    if decl in text:
        continue
    prev = max((int(x, 16) for x in re.findall(r'^void sub_([0-9A-F]{8})\(void\);$', text, re.M)
                if int(x, 16) < a), default=None)
    anchor = f'void sub_{prev:08X}(void);\n'
    text = text.replace(anchor, anchor + decl, 1)
funcs.write_text(text, encoding='utf-8', newline='\n')

disp = gen / 'recomp_dispatch.c'
text = disp.read_text(encoding='utf-8')
for a in MISSING:
    entry = f'    {{ 0x{a:08X}u, (recomp_func_t)sub_{a:08X} }},\n'
    if entry in text:
        continue
    rows = [(int(x, 16), x) for x in re.findall(r'^    \{ 0x([0-9A-F]{8})u, ', text, re.M)]
    prev = max(r for r in rows if r[0] < a)
    anchor = f'    {{ 0x{prev[1]}u, (recomp_func_t)sub_{prev[1]} }},\n'
    text = text.replace(anchor, anchor + entry, 1)
text = re.sub(r'static const size_t g_recomp_table_size = \d+;',
              'static const size_t g_recomp_table_size = sizeof g_recomp_table / sizeof g_recomp_table[0];',
              text)
disp.write_text(text, encoding='utf-8', newline='\n')
# A function that only had a "[UNRESOLVED] ... body unavailable" stub (a direct call into a split function) now has
# a body: drop the stub, or the link sees the symbol twice.
stubs = gen / 'recomp_stubs_unresolved.c'
if stubs.is_file():
    lines = stubs.read_text().splitlines(keepends=True)
    keep = [l for l in lines if not any(l.startswith(f'void sub_{a:08X}(void) {{ static int reported') for a in MISSING)]
    if len(keep) != len(lines):
        stubs.write_text(''.join(keep))
        print(f'removed {len(lines) - len(keep)} unresolved stub(s)')
print('dispatch and declarations updated')
